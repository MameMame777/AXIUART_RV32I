def main():
    parser = argparse.ArgumentParser(
        description='Generate project artifacts from VexRiscv RTL'
    )
    parser.add_argument(
        '--input',
        default='vexriscv_reference/generated/VexRiscv.v',
        help='Path to VexRiscv.v'
    )
    parser.add_argument(
        '--output-sv',
        default='generated/rtl/rv32i_decode_pkg.sv',
        help='SystemVerilog package output path'
    )
    
    args = parser.parse_args()
    
    # Check if input exists
    if not os.path.exists(args.input):
        print(f"ERROR: Input file not found: {args.input}")
        return 1
    
    # Parse RTL
    parser_obj = VexRiscvRTLParser(args.input)
    parser_obj.load()
    
    # Extract information
    enums = parser_obj.extract_enum_definitions()
    instructions = parser_obj.extract_instruction_patterns()
    
    # Generate artifacts
    parser_obj.generate_systemverilog_package(args.output_sv, instructions)
    
    print("\n=== Artifact Generation Complete ===")
    print(f"✓ SystemVerilog: {args.output_sv}")
    print("\nNote: cpu.yaml was not properly generated by VexRiscv YamlPlugin.")
    print("This tool extracted instruction definitions from RISC-V spec instead.")
    
    return 0


if __name__ == '__main__':
    exit(main())
