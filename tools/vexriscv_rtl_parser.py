    def __init__(self, verilog_path: str):
        self.verilog_path = verilog_path
        self.content = None
        self.instructions = {}
        self.opcodes = {}
        
    def load(self):
        """Load VexRiscv.v"""
        print(f"Loading {self.verilog_path}...")
        with open(self.verilog_path, 'r', encoding='utf-8') as f:
            self.content = f.read()
        print(f"  Loaded {len(self.content)} bytes")
        
    def extract_enum_definitions(self):
        """Extract enum definitions (opcodes, funct codes)"""
        print("\nExtracting enum definitions...")
        
        # Find all localparam definitions
        pattern = r'localparam\s+(\w+)\s*=\s*(\d+)\'d(\d+);'
        matches = re.findall(pattern, self.content)
        
        enums = {}
        for name, width, value in matches:
            enums[name] = {'width': int(width), 'value': int(value)}
        
        print(f"  Found {len(enums)} enum definitions")
        return enums
    
