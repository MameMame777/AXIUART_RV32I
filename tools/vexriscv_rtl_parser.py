#!/usr/bin/env python3
"""
VexRiscv RTL to Artifacts Generator

Since cpu.yaml is not properly generated by VexRiscv YamlPlugin,
this tool extracts instruction decode information directly from VexRiscv.v
and generates project artifacts.

Usage:
    python tools/vexriscv_rtl_parser.py
"""

